# start: the flame bursts out and reaches across in 4 frames, leading
#   straight into the loop.
# loop: the full jet, 8 frames; the turbulence travels one wavelength per loop,
#   so it repeats seamlessly, and sparks fly up off the top of the jet. Hold
#   the flamethrower on for as long as you like.
# end: the nozzle cuts out and the flame tears away from it, shrinking and
#   lifting as it throws up a big shower of sparks, which float up and burn
#   out at different heights; it ends empty. Every spark starts inside the
#   flame.
#   Play it from any loop frame.

