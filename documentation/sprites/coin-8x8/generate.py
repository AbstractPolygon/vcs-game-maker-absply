#!/usr/bin/env python3
"""Generates the 8x8, 10-frame circle spinning on its vertical axis in this
folder (see ../export_sprite.py for the formats). A prop, not the player."""
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from export_sprite import export  # noqa: E402

# A solid circle 6 pixels across, like a coin, centred in the 8x8 and spinning
# on its vertical axis. It narrows a pixel a frame from the full circle through
# ever thinner ellipses to edge on, then widens back. On the odd widths, which
# can't be centred, it leans a half pixel to the nearer side. A circle looks
# the same from behind, so the 10 frames are half a turn and the loop keeps
# spinning. Frame times follow a
# real spin and match the double jump power-up's speed (half a turn in 34 NTSC
# frames): it lingers face on and slips quickly through the narrow widths.
